/// 256 entries indexed by the TIA's pixel value (colour with D0 set; 0 is
/// blank, black), for `"ntsc"`, `"pal"` or `"secam"`.
pub fn palette(name: &str) -> Option<[[u8; 3]; 256]> {
    let table = match name {
        "ntsc" => &NTSC,
        "pal" => &PAL,
        "secam" => &SECAM,
        _ => return None,
    };
    let mut colours = [[0u8; 3]; 256];
    for value in (1..256).step_by(2) {
        let rgb = table[((value >> 1) & 7) * 16 + (value >> 4)];
        colours[value] = [(rgb >> 16) as u8, (rgb >> 8) as u8, rgb as u8];
    }
    Some(colours)
}
